"""Prompt for the extraction role: group blocks into requirements."""

from __future__ import annotations

from validator.models import Document
from validator.pipeline.prompts.render import render_document

TASK = """Задание: нарежь документ на требования.
Правила нарезки:
1. Требование — обязательство системы, ограничение, правило, бизнес-цель, описание процесса, интерфейса или данных, \
критерий приёмки. Каждый содержательный блок должен попасть либо в requirements, либо в skipped.
2. Запись с идентификатором из документа (например, «REQ-7», «4.2.1») не дробится, даже если она составная.
3. Блок без идентификатора с несколькими независимыми утверждениями дробится: одна запись на утверждение, \
в quote — дословный фрагмент блока, относящийся к этой записи.
4. Строка таблицы с содержанием (параметр интерфейса, поле данных, критерий приёмки, правило) — отдельная запись. \
Строки одной таблицы параметров интерфейса можно объединить в одну запись, только если они однотипны и \
малосодержательны.
5. Каждая строка таблицы критериев приёмки — отдельная запись типа acceptance_criterion.
6. В skipped: служебные поля (автор, проект, ссылки на трекер, подписи) — meta; незаполненные шаблоны и \
чек-листы с вариантами вместо значений — template; пустые разделы и заглушки — empty. Заголовки не включай никуда.
7. Примеры ответов интерфейса (блоки кода с JSON) включай в requirements как interface, если они задают формат.
8. doc_id — идентификатор из текста блока (если есть), иначе пустая строка. title — краткая формулировка по-русски \
до 100 символов. quote — пустая строка, если запись совпадает с блоком целиком; иначе дословный фрагмент.
9. kind: functional, nonfunctional, data, interface, integration, ui, business_goal, process, constraint, \
acceptance_criterion, other.
Верни JSON строго по схеме. Порядок записей — порядок документа."""


def build_extract_prompt(doc: Document) -> str:
    return render_document(doc) + "\n\n" + TASK
