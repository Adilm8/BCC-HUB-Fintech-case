# ---------------------------------------------------------------- rule hints

RULE_HINTS_NOTE = """В <rule_findings> — дефекты, которые уже нашли проверки по правилам. Не повторяй их: \
ищи остальные дефекты. Можно ссылаться на них, если твоя находка о другом аспекте того же места."""


def insert_rule_hints(prompt: str, hints: str) -> str:
    """The hint block goes right before the task, or at the end when the prompt has no task heading."""
    block = "<rule_findings>\n" + hints + "\n</rule_findings>\n" + RULE_HINTS_NOTE
    at = prompt.rfind("\n\nЗадание")
    if at < 0:
        return prompt + "\n\n" + block
    return prompt[:at] + "\n\n" + block + prompt[at:]


