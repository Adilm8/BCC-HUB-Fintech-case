SCENARIO_TASK = """Задание: ты — тестировщик-сценарист. Придумай 12–16 КОНКРЕТНЫХ сценариев с числами, датами, \
временем и последовательностями событий и проиграй каждый буквально по тексту документа.
Покрой:
- границу каждого порога и лимита: значение ровно на границе, на единицу меньше и больше;
- переход через полночь, конец месяца и конец расчётного периода;
- смену настройки, порога или состояния в середине периода, после того как событие уже произошло, и \
повторное наступление условия в том же периоде;
- повтор события, отмену и возврат (полный, частичный, за прошлый период);
- выключенный флаг или переключатель и значения по умолчанию;
- отказ, задержку или недоступность смежной системы;
- ответы интерфейса на неверные, отсутствующие и чужие данные;
- каждую строку критериев приёмки: её исходные условия, проигранные по правилам.
Для каждого сценария:
- scenario — входные данные и шаги с конкретными значениями;
- readings — каждое требование или строка критерия, которые применимы к сценарию: requirement_id, дословная \
цитата и что именно это место предписывает в этом сценарии;
- outcome — defined (все места дают один и тот же результат), undefined (ни одно место не говорит, что делать), \
contradictory (места дают разный результат).
Для undefined и contradictory заполни explanation (что именно расходится или чего не хватает), severity \
(расхождение в основном сценарии — critical, граница или альтернативный сценарий — major), recommendation, \
clarifying_question и answer_options. Для defined оставь их пустыми, severity minor.
Не придумывай правил, которых нет в тексте: каждое «предписывает» опирается на цитату."""


def build_scenario_prompt(doc: Document, reqs: list[Requirement], *, include_document: bool = True) -> str:
    parts = []
    if include_document:
        parts.append(render_document(doc))
    parts.append("<requirements>\n" + requirement_table(reqs, with_text=not include_document) + "\n</requirements>")
    parts.append(SCENARIO_TASK)
    return "\n\n".join(parts)


