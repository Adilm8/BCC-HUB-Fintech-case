# extra signs of violation that complement the shared definitions
EXTRA_SIGNS = {
    "appropriate": "бизнес-логика другой системы описана внутри спецификации интерфейса (смешение уровней)",
    "unambiguous": "неясная временная база или часовой пояс; неясно, что именно учитывается или считается",
    "complete": "не описано поведение при повторе, отмене или откате",
    "correct": "метод чтения, который меняет данные; код успеха для ошибки; пример противоречит правилу",
}
REQ_CODES = ["necessary", "appropriate", "unambiguous", "complete", "singular", "feasible", "verifiable",
             "correct", "conforming", "traceable"]
SET_CODES = ["set_complete", "set_consistent", "set_feasible", "set_comprehensible", "set_validatable", "ranked",
             "modifiable", "traceable"]


def criteria_text() -> str:
    """Criteria table built from the shared labels, so the report and the prompt use one definition."""
    try:
        from validator.models import Criterion
        from validator.report.labels import CRITERION_META
    except ImportError:
        return CRITERIA

    def line(code: str) -> str:
        m = CRITERION_META.get(Criterion(code))
        if m is None:
            return ""
        extra = EXTRA_SIGNS.get(code)
        signs = m.violation_signs.rstrip(".") + ("; " + extra if extra else "")
        return f"- {code} — {m.label.lower()}: {m.definition} Признаки нарушения: {signs}."

    req = [line(c) for c in REQ_CODES]
    req.append("- set_consistent — используй в проверке отдельного требования, только если оно противоречит "
               "другому требованию; тогда заполни related_requirement_ids.")
    sets = [line(c) for c in SET_CODES]
    nl = "\n"
    return ("Критерии отдельного требования (поле criterion):" + nl + nl.join(x for x in req if x)
            + nl + nl + "Критерии набора (поле criterion в проверке набора):" + nl
            + nl.join(x for x in sets if x))


def system_prompt(*, with_api: bool = True) -> str:
    parts = [ROLE, criteria_text(), SEVERITY, FINDING_RULES]
    if with_api:
        parts += [API_CHECKLIST, SECURITY_LENS]
    parts.append(INJECTION)
    return "\n\n".join(parts)


